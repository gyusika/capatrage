-- 더미 가격(슬롯 차단용 허위 단가) 제외.
--
-- 실측하다 잡은 오류다. 예약된 시각의 단가에 1,000,000 / 999,900 / 2,000,000 같은
-- 값이 섞여 있다. 사장이 그 시간대를 팔지 않으려고 넣는 값으로 보인다.
-- 이걸 매출로 세면 시간당 100만원짜리 강의실이 288시간 예약된 것이 되어
-- 월 매출 8억이 나온다.
--
-- 규모: 예약된 171,685시간 중 20만원 이상이 1,117시간(0.65%)인데
--       그 0.65%가 계산된 매출 36.6억 중 6.4억(17.6%)을 만들고 있었다.
--
-- 판정 기준은 절대 금액이 아니라 "그 상품 자신의 통상 단가 대비 배수"다.
-- 업종마다 정상 단가가 다르기 때문이다(연습실 9천원 ~ 숙박 7만원).
-- 배수 분포가 이봉이라 경계가 데이터에서 저절로 나온다:
--
--   2배 미만    246,143시간   매출 92.4%   ← 정상
--   2~3배         3,962시간   매출  3.1%   ← 주말·피크 할증
--   3~5배           584시간   매출  0.2%
--   5~10배          251시간   매출  0.2%
--   10~20배          14시간   매출  0.0%   ← 골짜기
--   20배 이상       228시간   매출  4.2%   ← 시간당 평균 163만원. 다른 모집단이다.
--
-- 10~20배 구간이 14시간뿐인 골짜기라 10배를 경계로 잡는다. 임의값이 아니다.
-- 통상 단가는 그 상품에서 관측된 모든 시간 단가의 중앙값으로 잡는다.
--
-- 더미로 판정된 시각은 예약(분자)에서도 영업시간(분모)에서도 뺀다.
-- 팔린 것도 아니고 팔 수 있는 것도 아니기 때문이다. 휴무와 같은 취급이다.

alter table space_revenue add column if not exists dummy_h   int;
alter table space_revenue add column if not exists dummy_rev numeric(14,0);

comment on column space_revenue.dummy_h   is '더미 가격으로 판정해 제외한 시간 수';
comment on column space_revenue.dummy_rev is '제외하지 않았다면 매출로 잡혔을 금액';
